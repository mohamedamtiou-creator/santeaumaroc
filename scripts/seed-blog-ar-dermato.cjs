async function main() {
  let n = 0;
  for (const t of TRANSLATIONS) {
    const post = await prisma.post.findUnique({ where: { slug: t.slug }, select: { id: true, arReviewedAt: true } });
    if (!post) { console.error(`✗ article « ${t.slug} » introuvable`); continue; }
    await prisma.post.update({
      where: { id: post.id },
      data: {
        titleAr: t.titleAr,
        excerptAr: t.excerptAr,
        metaTitleAr: t.metaTitleAr,
        metaDescAr: t.metaDescAr,
        contentAr: t.contentAr,
        keyTakeawaysAr: t.keyTakeawaysAr.join("\n"),
        faqJsonAr: JSON.stringify(t.faqAr),
      },
    });
    const words = t.contentAr.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim().split(" ").filter(Boolean).length;
    console.log(`✓ ${t.slug.padEnd(28)} ${words} mots AR · ${t.faqAr.length} FAQ · ${t.keyTakeawaysAr.length} points${post.arReviewedAt ? "" : " · non publié (verrou AR)"}`);
    n++;
  }
  console.log(`\n${n} traduction(s) enregistrée(s). L'arabe reste en attente de relecture humaine (arReviewedAt non posé).`);
}

